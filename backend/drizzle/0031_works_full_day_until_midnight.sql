-- Миграция: рабочий день календаря работ — 08:00–24:00 (строки часов 08:00 … 23:00).
-- Импортированные из старой системы работы были на целый день — растягиваем до 24:00,
-- чтобы они попадали во все часовые строки, включая 23:00.
UPDATE works SET end_time = '24:00'
WHERE legacy_id IS NOT NULL AND start_time = '08:00' AND end_time = '23:00';
